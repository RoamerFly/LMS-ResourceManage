const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');

module.exports = async ({evaluate,call,click,delay,restartBackend}) => {
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  const waitFor = async expression => {
    for (let i=0;i<100;i++) { if (await evaluate(expression)) return; await delay(100); }
    throw new Error(`页面未就绪：${expression}`);
  };
  const loaded = () => waitFor(`document.getElementById('loadingOverlay')?.style.display==='none'`);
  const ready = wrap => waitFor(`LmsSpreadsheet.getInstance('${wrap}')?.ready && !document.querySelector('#${wrap} [data-u-comp="workbench-skeleton-shimmer"]')`);
  const size = selector => evaluate(`parseFloat(getComputedStyle(document.querySelector(${JSON.stringify(selector)})).fontSize)`);
  const fonts = () => evaluate(`(() => {const s=LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet();return [s.getRange(0,3).getCellStyleData().fs,s.getRange(1,3).getCellStyleData().fs];})()`);
  await loaded();
  assert.equal(await evaluate(`_currentSettings.fontScale`),'100','旧版默认字号迁移为100%');
  assert.equal(await evaluate(`normalizeSettings({'fontSize-base':'18','table-fontSize':'17'}).fontScale`),'138','旧版字号迁移为整体缩放百分比');
  await click('.nav-item[data-view="settings"]');
  await click('.settings-nav-item[data-settings="fonts"]');
  assert.equal(await evaluate(`document.querySelectorAll('#settings-fonts input[type=range]').length`),1,'字体设置只有一项缩放');
  assert.equal(await evaluate(`document.getElementById('s-table-fontSize')`),null,'移除单独表格字号滑块');
  await evaluate(`document.getElementById('s-fontScale').value='150';document.getElementById('s-fontScale').dispatchEvent(new Event('input'))`);
  await delay(250);
  assert.equal(await size('.nav-item[data-view="settings"]'),21,'导航按150%缩放');
  assert.equal(await size('.topbar-title'),30,'页面标题按150%缩放');
  assert.equal(await evaluate(`document.getElementById('s-fontScale-val').textContent`),'150%','显示百分比而非px');
  await click('.nav-item[data-view="members"]');
  await waitFor(`document.querySelector('.member-card .member-name')!==null`);
  assert.equal(await size('.member-card .member-name'),33,'人员姓名按150%缩放');
  assert.equal(await size('.member-card .member-wage'),30,'人员工资按相同比例放大');
  await click('.nav-item[data-view="salary"]');
  await waitFor(`document.querySelector('#view-salary table td')!==null`);
  assert.equal(await size('#view-salary table'),22.5,'工资表正文按150%缩放');
  await click('.nav-item[data-view="quickcalc"]');
  await ready('qcDeptTablesWrap');
  const tabSelector='#qcDeptTablesWrap [data-u-comp="slide-tab-item"]';
  assert.equal(await size(tabSelector),24,'工作表标签以16px为基准按150%放大');
  assert.ok(await evaluate(`(() => {const tab=document.querySelector('${tabSelector}'),footer=tab.closest('section');return tab.getBoundingClientRect().height<=footer.getBoundingClientRect().height && tab.firstElementChild.scrollWidth<=tab.firstElementChild.clientWidth;})()`),'放大标签完整显示，底部区域适应高度');
  await click('#qcDeptTablesWrap [data-u-comp="slide-tab-item"][data-id="dept-2"]');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getSheetId()`),'dept-2','放大标签可正常切换工作表');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,3).setValue(0);void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(0,3).setBackgroundColor('#abcdef');applySetting('fontScale','200',true)`);
  assert.deepEqual(await fonts(),[26,26],'已挂载Canvas表头与内容实时按比例缩放');
  assert.equal(await size(tabSelector),32,'工作表标签同步放大到32px');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getSheetId()`),'dept-2','调整缩放保留活动工作表');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,3).getRawValue()`),0,'缩放保留显式零值');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(0,3).getCellStyleData().bg.rgb`),'#abcdef','缩放保留其他手动样式');
  await evaluate(`applySetting('table-compact',true,true)`);
  assert.deepEqual(await fonts(),[26,26],'紧凑模式不覆盖字体缩放');
  await evaluate(`(async()=>{applySetting('table-compact',false,true);await autoSaveQc();await saveSettings(true);await initQuickCalc();})()`);
  await ready('qcDeptTablesWrap');
  assert.deepEqual(await fonts(),[26,26],'已保存布局不覆盖字体缩放');
  await evaluate(`qcToggleViewMode()`); await ready('qcDeptTablesWrap');
  assert.deepEqual(await fonts(),[26,26],'工资视角也按相同比例放大');
  await evaluate(`(async()=>{await qcToggleViewMode();applySetting('fontScale','150',true);await undo();})()`); await ready('qcDeptTablesWrap');
  assert.deepEqual(await fonts(),[19.5,19.5],'撤销业务数据不撤销字体缩放');
  await evaluate(`(async()=>{applySetting('minimalMode',true,true);await navigateTo('quickcalc');})()`); await ready('qcDeptTablesWrap');
  assert.equal(await size('#minimalNav .minimal-calculate'),24,'极简导航同比例放大');
  const shot = await call('Page.captureScreenshot',{format:'png'});
  const file = path.join(os.tmpdir(),'lms-font-scale-tabs.png');
  await fs.writeFile(file,Buffer.from(shot.data,'base64')); console.log('SCREENSHOT: '+file);
  await evaluate(`saveSettings(true)`); await restartBackend(); await call('Page.reload'); await loaded(); await ready('qcDeptTablesWrap');
  assert.deepEqual(await fonts(),[19.5,19.5],'重启后Canvas缩放保留');
  assert.equal(await size(tabSelector),24,'重启后工作表标签同比例放大');
  assert.equal(await evaluate(`get('/api/app-settings-all').then(settings=>Number(settings.ui_fontScale))`),150,'字体缩放保存到SQLite');
  await click('#minimalSettingsBtn'); await delay(300); await click('.settings-nav-item[data-settings="fonts"]');
  assert.equal(await evaluate(`document.getElementById('s-fontScale').value`),'150','重启后设置控件与实际缩放一致');
  const settingsShot = await call('Page.captureScreenshot',{format:'png'});
  await fs.writeFile(path.join(os.tmpdir(),'lms-font-scale-settings.png'),Buffer.from(settingsShot.data,'base64'));
  console.log('PASS: 单项等比例字体缩放/旧设置迁移/工作表标签放大与实际切换/Canvas实时缩放/样式与零值保留/重新加载与工资视角/撤销及SQLite重启');
};
