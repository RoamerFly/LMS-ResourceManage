const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');

module.exports=async({evaluate,call,click,key,delay})=>{
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  const waitFor=async expression=>{for(let i=0;i<100;i++){if(await evaluate(expression))return;await delay(100);}throw new Error(`页面未就绪：${expression}`);};
  const ready=wrap=>waitFor(`LmsSpreadsheet.getInstance('${wrap}')?.ready && !document.querySelector('#${wrap} [data-u-comp="workbench-skeleton-shimmer"]')`);
  const position=wrap=>evaluate(`(() => {const s=LmsSpreadsheet.getInstance('${wrap}').book.getActiveSheet(),c=s.getSelection().getCurrentCell();return [s.getSheetId(),c.actualRow,c.actualColumn];})()`);
  const search=async(page,text)=>{
    await click(`#sheetSearch_${page} input`);await key('a',65,2);await call('Input.insertText',{text});await delay(350);
  };
  await waitFor(`document.getElementById('loadingOverlay')?.style.display==='none'`);
  await click('.nav-item[data-view="quickcalc"]');await ready('qcDeptTablesWrap');
  const qc='qcDeptTablesWrap';
  assert.equal(await evaluate(`document.getElementById('memberOrderSync_quickcalc').nextElementSibling.id`),'sheetSearch_quickcalc','搜索框紧邻同步成员顺序右侧');
  await key('f',70,2);
  assert.equal(await evaluate(`document.activeElement===document.querySelector('#sheetSearch_quickcalc input')`),true,'Ctrl+F聚焦应用搜索框');
  await search('quickcalc','李四');
  assert.deepEqual(await position(qc),['dept-1',0,7],'搜索人员名定位只读表头，不弹人员窗口');
  assert.equal(await evaluate(`document.querySelector('.modal-overlay.show')`),null,'搜索不触发编辑人员');
  await evaluate(`(() => {const i=LmsSpreadsheet.getInstance('${qc}');i.book.getActiveSheet().getRange(1,0,60,1).setValues(Array.from({length:60},(_,n)=>['单-'+(n+1)]));i.book.getActiveSheet().getRange(2,0).setValue('000ABC');i.book.getActiveSheet().getRange(55,0).setValue('000ABC');i.book.getActiveSheet().getRange(1,3).setValue(99.875);i.book.getActiveSheet().getRange(1,6).setValue(0);i.book.setActiveSheet('dept-2').getRange(1,0).setValue('000ABC');i.book.setActiveSheet('dept-1');clearHistory();})()`);
  await search('quickcalc','000abc');
  assert.deepEqual(await position(qc),['dept-1',2,0],'订单号支持前导零和大小写无关匹配');
  assert.equal(await evaluate(`document.querySelector('#sheetSearch_quickcalc .sheet-search-count').textContent`),'1/3','显示跨工作表匹配总数');
  await key('Enter',13);await delay(100);
  assert.deepEqual(await position(qc),['dept-1',55,0],'Enter定位远处匹配');
  assert.ok(await evaluate(`(() => {const v=LmsSpreadsheet.getInstance('${qc}').book.getActiveSheet().getVisibleRange();return v.startRow<=55&&v.endRow>=55;})()`),'滚动使匹配单元格可见');
  await key('Enter',13);await delay(100);
  assert.deepEqual(await position(qc),['dept-2',1,0],'下一匹配自动切换工作表');
  await key('Enter',13);await delay(100);assert.deepEqual(await position(qc),['dept-1',2,0],'最后一项循环到第一项');
  await key('Enter',13,8);await delay(100);assert.deepEqual(await position(qc),['dept-2',1,0],'Shift+Enter定位上一个');
  await click('#sheetSearch_quickcalc button[aria-label="下一个匹配单元格"]');await delay(100);
  assert.deepEqual(await position(qc),['dept-1',2,0],'搜索框箭头按钮可导航');
  const before=await position(qc);
  await search('quickcalc','不存在的单元格');assert.deepEqual(await position(qc),before,'无结果保留原选区');
  assert.equal(await evaluate(`document.querySelector('#sheetSearch_quickcalc .sheet-search-count').textContent`),'无结果','无结果明确反馈');
  assert.equal(await evaluate(`document.querySelector('#sheetSearch_quickcalc button').disabled`),true,'无结果禁用导航');
  await search('quickcalc','99.88');assert.deepEqual(await position(qc),['dept-1',1,3],'搜索格式化后的显示数值');
  await search('quickcalc','99.875');assert.deepEqual(await position(qc),['dept-1',1,3],'搜索原始精确数值');
  assert.equal(await evaluate('_undoStack.length'),0,'搜索定位不产生数据历史');
  await search('quickcalc','0');assert.ok(await evaluate(`document.querySelector('#sheetSearch_quickcalc .sheet-search-count').textContent!=='无结果'`),'显式零可搜索');
  await key('Escape',27);assert.equal(await evaluate(`document.querySelector('#sheetSearch_quickcalc input').value`),'','Escape清空搜索');
  assert.equal(await evaluate(`document.activeElement.getAttribute('data-u-comp')`),'editor','Escape焦点回到电子表格');
  await evaluate(`void LmsSpreadsheet.getInstance('${qc}').book.getActiveSheet().setActiveRange(LmsSpreadsheet.getInstance('${qc}').book.getActiveSheet().getRange(1,3))`);
  await key('F2',113);await key('a',65,2);await call('Input.insertText',{text:'123.456'});await key('f',70,2);await delay(100);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('${qc}').book.getActiveSheet().getRange(1,3).getRawValue()`),123.456,'编辑中Ctrl+F先提交输入值');
  assert.equal(await evaluate(`document.activeElement===document.querySelector('#sheetSearch_quickcalc input')`),true,'编辑中Ctrl+F仍能聚焦搜索');
  await search('quickcalc','123.456');assert.deepEqual(await position(qc),['dept-1',1,3],'刚编辑的值立即可检索');
  const historyBefore=await evaluate('_undoStack.length');await key('z',90,2);await delay(100);
  assert.equal(await evaluate('_undoStack.length'),historyBefore,'搜索框Ctrl+Z不撤销工资数据');
  await evaluate(`(async()=>{applySetting('minimalMode',true,true);await navigateTo('quickcalc');})()`);await ready(qc);
  await search('quickcalc','李四');assert.deepEqual(await position(qc),['dept-1',0,7],'极简模式搜索可用');
  const shot=await call('Page.captureScreenshot',{format:'png'});await fs.writeFile(path.join(os.tmpdir(),'lms-cell-search.png'),Buffer.from(shot.data,'base64'));
  assert.equal(await evaluate(`document.querySelectorAll('#sheetSearch_quickcalc').length`),1,'重建工作簿不重复添加搜索框');
  await evaluate(`(async()=>{applySetting('minimalMode',false,true);await navigateTo('work');})()`);await ready('spreadsheetWrap');
  assert.equal(await evaluate(`document.getElementById('memberOrderSync_work').nextElementSibling.id`),'sheetSearch_work','做货页搜索框在顺序同步右侧');
  await key('f',70,2);assert.equal(await evaluate(`document.activeElement===document.querySelector('#sheetSearch_work input')`),true,'做货页Ctrl+F');
  await search('work','A001');assert.deepEqual((await position('spreadsheetWrap')).slice(1),[2,0],'做货页搜索订单定位');
  console.log('PASS: Ctrl+F/搜索框位置/人员与订单/跨表循环/滚动定位/原值及显示值/无结果/编辑提交/搜索框文本撤销/极简与做货页');
};
