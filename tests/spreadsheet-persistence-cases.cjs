const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');

module.exports = async ({evaluate,call,click,key,mouse,delay,restartBackend}) => {
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  const waitFor = async expression => {
    for (let i=0;i<100;i++) {
      if (await evaluate(expression)) return;
      await delay(100);
    }
    throw new Error(`页面未就绪：${expression}`);
  };
  const ready = wrap => waitFor(`window.LmsSpreadsheet?.getInstance('${wrap}')?.ready === true && !document.querySelector('#${wrap} [data-u-comp="workbench-skeleton-shimmer"]')`);
  const cell = (wrap,r,c) => evaluate(`Number(LmsSpreadsheet.getInstance('${wrap}').book.getActiveSheet().getRange(${r},${c}).getValue())`);
  const select = async (wrap,r,c,count=1) => {
    await ready(wrap);
    const at = await evaluate(`(() => {const rect=LmsSpreadsheet.getInstance('${wrap}').book.getActiveSheet().getRange(${r},${c}).getCellRect();const canvas=Array.from(document.querySelectorAll('#${wrap} canvas'),el=>el.getBoundingClientRect()).sort((a,b)=>b.width*b.height-a.width*a.height)[0];return {x:canvas.x+rect.x+rect.width/2,y:canvas.y+rect.y+rect.height/2};})()`);
    for (let n=1;n<=count;n++) {
      await mouse('mousePressed',at,{button:'left',buttons:1,clickCount:n});
      await mouse('mouseReleased',at,{button:'left',buttons:0,clickCount:n});
    }
    await delay(80);
    await waitFor(`(() => {const range=LmsSpreadsheet.getInstance('${wrap}').book.getActiveSheet().getSelection()?.getActiveRange()?.getRange();return range?.startRow===${r} && range?.startColumn===${c};})()`);
  };
  const type = async text => {
    await waitFor(`document.activeElement?.getAttribute('data-u-comp')==='editor'`);
    for (const ch of text) {
      await call('Input.dispatchKeyEvent',{type:'keyDown',key:ch,windowsVirtualKeyCode:ch==='.'?190:ch.charCodeAt(0),text:ch});
      await call('Input.dispatchKeyEvent',{type:'keyUp',key:ch,windowsVirtualKeyCode:ch==='.'?190:ch.charCodeAt(0)});
    }
  };
  const savedWork = () => evaluate(`get('/api/work-records?year=2026&month=9').then(data=>data.records.find(row=>row.emp_id===1&&row.order_id===1&&row.model_id===1)?.quantity)`);
  const savedQc = month => evaluate(`get('/api/quick-calc-save?year=2026&month=${month}')`);
  const noActionsInCells = wrap => evaluate(`(() => {const sheets=LmsSpreadsheet.getInstance('${wrap}').book.save().sheets;return Object.values(sheets).every(sheet=>Object.values(sheet.cellData).every(row=>Object.values(row).every(cell=>!['删除','操作'].includes(cell.v))));})()`);

  await waitFor(`document.getElementById('loadingOverlay')?.style.display === 'none'`);
  assert.equal(await evaluate(`_currentSettings['sidebar-width']`),'auto','旧默认侧栏迁移为适应文字');
  const width = await evaluate(`document.querySelector('.sidebar').getBoundingClientRect().width`);
  assert.ok(width>100 && width<180,`紧凑导航宽度 ${width}px`);
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('.sidebar .nav-item,.sidebar-logo'),el=>el.scrollWidth<=el.clientWidth).every(Boolean)`),true,'导航和标题完整显示');
  assert.equal(await evaluate(`get('/api/window/settings').then(result=>result.config.maximized)`),true,'API默认最大化');
  await evaluate(`applySetting('fontSize-base','20',true)`);
  await delay(250);
  assert.ok(await evaluate(`document.querySelector('.sidebar').getBoundingClientRect().width`) > width,'字体放大后侧栏自适应');
  await evaluate(`applySetting('fontSize-base','13',true)`);
  await delay(250);

  await click('.nav-item[data-view="work"]');
  await ready('spreadsheetWrap');
  await delay(400);
  assert.equal(await noActionsInCells('spreadsheetWrap'),true,'做货格子没有操作列');
  assert.ok(await evaluate(`document.querySelector('#spreadsheetWrap .lms-sheet-actions').textContent.includes('删除选中行')`),'删除留在工具栏');
  await select('spreadsheetWrap',2,2);
  await type('123');
  await key('Enter',13);
  await delay(150);
  assert.equal(await cell('spreadsheetWrap',2,2),123,'直接键入多位数字持续可见');
  await click('#workSaveBtn');
  await waitFor(`document.getElementById('workSaveBtn').textContent.includes('已保存')`);
  assert.equal(await savedWork(),123,'做货实际数据库保存');

  await select('spreadsheetWrap',2,2,2);
  await key('a',65,2);
  await type('456');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.isCellEditing()`),true,'双击编辑状态');
  await click('#workSaveBtn');
  await waitFor(`!LmsSpreadsheet.getInstance('spreadsheetWrap').book.isCellEditing()`);
  await waitFor(`get('/api/work-records?year=2026&month=9').then(data=>data.records.some(row=>row.emp_id===1&&row.quantity===456))`);
  assert.equal(await cell('spreadsheetWrap',2,2),456,'未按Enter直接点保存也显示新值');
  await evaluate('loadWorkRecords()');
  await delay(150);
  assert.equal(await cell('spreadsheetWrap',2,2),456,'刷新从SQLite恢复');
  await select('spreadsheetWrap',2,2);
  await type('789');
  await click('.nav-item[data-view="quickcalc"]');
  await ready('qcDeptTablesWrap');
  await delay(400);
  assert.equal(await savedWork(),789,'编辑中切换页面先保存');
  assert.equal(await noActionsInCells('qcDeptTablesWrap'),true,'快捷计算格子没有操作列');
  const priceCol = await evaluate(`Array.from(Array.from(LmsSpreadsheet.getInstance('qcDeptTablesWrap').sheets.values())[0].cells.values()).find(cell=>cell.isPrice && cell.input.dataset.subId==='1').col`);
  const qtyCol = await evaluate(`Array.from(Array.from(LmsSpreadsheet.getInstance('qcDeptTablesWrap').sheets.values())[0].cells.values()).find(cell=>cell.input?.classList.contains('qc-qty-input') && cell.input.dataset.key==='1_0,1').col`);

  await select('qcDeptTablesWrap',1,0);
  await type('000123');
  await key('Tab',9);
  await type('100');
  await key('Enter',13);
  assert.equal(await evaluate(`_qcState.rowMeta['1_0'].orderNo`),'000123','真实键盘录入文本订单号保留前导零');
  assert.equal(await evaluate(`isQcRowUsed('1_0')`),true,'仅填写订单信息即启用行');
  await select('qcDeptTablesWrap',1,priceCol);
  await type('2.75');
  await key('Tab',9);
  await delay(100);
  assert.equal(await cell('qcDeptTablesWrap',1,priceCol),2.75,'单价小数可见');
  await select('qcDeptTablesWrap',1,qtyCol);
  await type('42');
  await click('#qcSaveBtn');
  await waitFor(`get('/api/quick-calc-save?year=2026&month=9').then(data=>data.qty_data?.['1_0,1']===42)`);
  assert.deepEqual((await savedQc(9)).row_meta['1_0'],{orderNo:'000123',orderQty:100},'订单核对信息保存到SQLite');
  assert.equal(await cell('qcDeptTablesWrap',1,2),42,'已做数量自动同步');
  assert.equal((await savedQc(9)).dept_rows['1_0'][1],2.75,'单价写入实际数据库');
  assert.equal(await cell('qcDeptTablesWrap',1,qtyCol),42,'编辑中直接保存对数');
  await select('qcDeptTablesWrap',1,qtyCol);
  await type('88');
  await evaluate(`document.getElementById('qcMonth').value='10'; document.getElementById('qcMonth').dispatchEvent(new Event('change'));`);
  await waitFor(`_qcLoadedPeriod?.month===10`);
  await delay(250);
  assert.equal((await savedQc(9)).qty_data['1_0,1'],88,'切月前数据保存到原月份');
  assert.deepEqual(await evaluate('_qcState.rowMeta'),{},'新月份订单核对信息不串月');
  assert.equal(await cell('qcDeptTablesWrap',1,qtyCol),0,'新月份没有带入旧数据');
  assert.equal(Object.keys((await savedQc(10))?.qty_data||{}).length,0,'新月份数据库未被旧数据污染');

  await restartBackend();
  await call('Page.reload');
  await waitFor(`document.getElementById('loadingOverlay')?.style.display === 'none'`);
  await click('.nav-item[data-view="work"]');
  await ready('spreadsheetWrap');
  await delay(350);
  assert.equal(await cell('spreadsheetWrap',2,2),789,'重启服务及页面后做货数据恢复');
  await select('spreadsheetWrap',2,2);
  await type('321');
  await key('ArrowRight',39);
  await delay(150);
  assert.equal(await cell('spreadsheetWrap',2,2),321,'编辑中方向键提交数值');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getSelection().getActiveRange().getA1Notation()`),'D3','方向键移动到右侧格子');
  const shot = await call('Page.captureScreenshot',{format:'png'});
  const screenshot = path.join(os.tmpdir(),'lms-spreadsheet-save-layout.png');
  await fs.writeFile(screenshot,Buffer.from(shot.data,'base64'));
  console.log(`SCREENSHOT: ${screenshot}`);
  await click('.nav-item[data-view="quickcalc"]');
  await ready('qcDeptTablesWrap');
  await delay(350);
  assert.equal(await cell('qcDeptTablesWrap',1,priceCol),2.75,'重启后恢复快捷计算单价');
  assert.equal(await cell('qcDeptTablesWrap',1,qtyCol),88,'重启后恢复快捷计算对数');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,0).getRawValue()`),'000123','切月与重启后恢复订单号文本');
  assert.equal(await cell('qcDeptTablesWrap',1,1),100,'重启恢复订单数量');
  assert.equal(await cell('qcDeptTablesWrap',1,2),88,'重启自动计算已做数量');
  assert.equal(await evaluate(`document.querySelector('#view-quickcalc .lms-sheet-hint')`),null,'精简页面不含选格说明');
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('#view-quickcalc button')).some(button=>/添加行|添加一行|删除选中行/.test(button.textContent))`),false,'页面不含添加和删除行按钮');
  const layout = await evaluate(`(() => {const host=document.querySelector('#qcDeptTablesWrap .lms-sheet-host').getBoundingClientRect();return {top:host.top,bottom:host.bottom,height:host.height,viewport:innerHeight};})()`);
  assert.ok(layout.top<=115 && layout.height>=layout.viewport-135 && layout.bottom<=layout.viewport,`1000px窗口表格占满剩余空间 ${JSON.stringify(layout)}`);
  await select('qcDeptTablesWrap',5,priceCol);
  await type('1.25');
  await key('Enter',13);
  await delay(80);
  assert.equal(await evaluate(`isQcRowUsed('1_4')`),false,'真实键盘跳过空行不能编辑');
  assert.equal(await cell('qcDeptTablesWrap',5,priceCol),0,'跳行录入不留下可见值');
  await select('qcDeptTablesWrap',2,priceCol);
  await type('1.25');
  await key('Enter',13);
  await delay(80);
  await select('qcDeptTablesWrap',2,qtyCol);
  await type('17');
  await key('Enter',13);
  await delay(80);
  await select('qcDeptTablesWrap',3,qtyCol);
  await type('9');
  await click('#qcSaveBtn');
  await waitFor(`get('/api/quick-calc-save?year=2026&month=9').then(data=>data.qty_data['1_2,1']===9)`);
  let qc = await savedQc(9);
  assert.equal(qc.dept_rows['1_1'][1],1.25,'连续新增行单价写入数据库');
  assert.equal(qc.qty_data['1_1,1'],17,'连续新增行对数写入数据库');
  assert.equal(qc.dept_rows['1_3'],undefined,'空白占位行不写入数据库');
  assert.equal(qc.dept_rows['1_2'][1],undefined,'只填对数也能启用行');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(4,${qtyCol},3,1).setValues([[4],[''],[6]])`);
  assert.equal(await evaluate(`isQcRowUsed('1_3') || isQcRowUsed('1_5')`),false,'包含空行的跨行粘贴整块拒绝');
  await evaluate('initQuickCalc()');
  await delay(150);
  assert.equal(await cell('qcDeptTablesWrap',2,qtyCol),17,'刷新后连续数据恢复');
  assert.equal(await cell('qcDeptTablesWrap',3,qtyCol),9,'只填员工列的行也恢复');
  await select('qcDeptTablesWrap',2,qtyCol);
  await key('Delete',46);
  await delay(80);
  assert.equal(await evaluate(`isQcRowUsed('1_1')`),true,'仅清空对数时单价仍使行保持在用');
  const dataColumns = await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.save().sheets['dept-1'].columnCount`);
  assert.equal(dataColumns,await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').sheets.get('dept-1').columnCount`),'不生成表头范围之外的空白列');
  await assert.rejects(evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,${dataColumns}).setValue(25)`),/Range is out of bounds/,'表头之外不存在可写入列');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().setActiveRange(LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(2,0,1,${dataColumns}))`);
  await key('Delete',46);
  await delay(80);
  assert.equal(await cell('qcDeptTablesWrap',2,qtyCol),9,'清空中间整行后后续数据向上补齐');
  assert.equal(await cell('qcDeptTablesWrap',3,qtyCol),0,'收拢后的末行数据清空');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(3,${priceCol}).getCellStyleData().bg.rgb`),'#ffffff','收拢后的末行恢复空白样式');
  await evaluate('undo()');
  await delay(150);
  assert.equal(await cell('qcDeptTablesWrap',2,priceCol),1.25,'撤销恢复被清空行');
  assert.equal(await cell('qcDeptTablesWrap',3,qtyCol),9,'撤销恢复后续行位置');
  await evaluate('redo()');
  await delay(150);
  assert.equal(await cell('qcDeptTablesWrap',2,qtyCol),9,'重做再次收拢数据');
  await click('#qcSaveBtn');
  await waitFor(`get('/api/quick-calc-save?year=2026&month=9').then(data=>data.qty_data['1_1,1']===9 && !data.dept_rows['1_2'])`);
  await restartBackend();
  await call('Page.reload');
  await waitFor(`document.getElementById('loadingOverlay')?.style.display === 'none'`);
  await click('.nav-item[data-view="quickcalc"]');
  await ready('qcDeptTablesWrap');
  await delay(350);
  assert.equal(await cell('qcDeptTablesWrap',2,qtyCol),9,'收拢行重启后仍保持连续');
  assert.equal(await cell('qcDeptTablesWrap',3,qtyCol),0,'收拢后的空白末行重启后不复活');
  await call('Browser.grantPermissions',{permissions:['clipboardReadWrite','clipboardSanitizedWrite']});
  const xlsxHtml = '<html xmlns:x="urn:schemas-microsoft-com:office:excel"><body><table><tr><td style="background:#fff;font-size:18pt">88</td><td style="background:#fff;font-size:18pt"></td></tr><tr><td style="background:#fff;font-size:18pt">9</td><td style="background:#fff;font-size:18pt"></td></tr></table></body></html>';
  for (let i=0;i<2;i++) {
    await select('qcDeptTablesWrap',1,qtyCol);
    await evaluate(`navigator.clipboard.write([new ClipboardItem({'text/plain':new Blob(['88\\t\\n9\\t'],{type:'text/plain'}),'text/html':new Blob([${JSON.stringify(xlsxHtml)}],{type:'text/html'})})])`);
    await key('v',86,2);
    await delay(150);
  }
  const usedColors = () => evaluate(`(() => {const s=LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet();return [1,2].map(r=>[${qtyCol},${qtyCol+1}].map(c=>s.getRange(r,c).getCellStyleData().bg.rgb));})()`);
  const usedFontSizes = () => evaluate(`(() => {const s=LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet();return [1,2].map(r=>[${qtyCol},${qtyCol+1}].map(c=>s.getRange(r,c).getCellStyleData().fs));})()`);
  assert.deepEqual(await usedColors(),[['#eff6ff','#eff6ff'],['#eff6ff','#eff6ff']],'重复XLSX粘贴空格后，有值行的所有人员格仍在用');
  assert.deepEqual(await usedFontSizes(),[[13,13],[13,13]],'粘贴使用本表字号，不带入XLSX的18号字体');
  await click('#qcSaveBtn');
  await waitFor(`get('/api/quick-calc-save?year=2026&month=9').then(data=>data.qty_data['1_0,1']===88 && data.qty_data['1_1,1']===9)`);
  await delay(700);
  await restartBackend();
  await call('Page.reload');
  await waitFor(`document.getElementById('loadingOverlay')?.style.display === 'none'`);
  await click('.nav-item[data-view="quickcalc"]');
  await ready('qcDeptTablesWrap');
  await delay(350);
  assert.deepEqual(await usedColors(),[['#eff6ff','#eff6ff'],['#eff6ff','#eff6ff']],'粘贴行样式保存和重启后保持一致');
  assert.deepEqual(await usedFontSizes(),[[13,13],[13,13]],'保存与重启后仍保持目标表格字体');
  assert.equal(await cell('qcDeptTablesWrap',1,qtyCol),88,'稀疏粘贴重启后数值保留');
  await select('qcDeptTablesWrap',3,priceCol);
  await waitFor(`document.activeElement?.getAttribute('data-u-comp')==='editor'`);
  const bulkHtml = '<table>'+Array.from({length:500},()=>'<tr><td style="font-size:22pt"><b>￥1.70&nbsp;</b></td></tr>').join('')+'</table>';
  await evaluate(`navigator.clipboard.write([new ClipboardItem({'text/plain':new Blob([Array.from({length:500},()=>'￥1.70\\u00a0').join('\\n')],{type:'text/plain'}),'text/html':new Blob([${JSON.stringify(bulkHtml)}],{type:'text/html'})})])`);
  await key('v',86,2);
  await waitFor(`getQcUsedRowCount(1)===502`);
  assert.equal(await evaluate(`_qcDeptRows['1_501'][1]`),1.7,'500行人民币金额直接启用未使用行，最后一行未截断');
  await click('#qcSaveBtn');
  await waitFor(`get('/api/quick-calc-save?year=2026&month=9').then(data=>data.dept_rows['1_501']?.[1]===1.7)`);
  await restartBackend();
  await call('Page.reload');
  await waitFor(`document.getElementById('loadingOverlay')?.style.display === 'none'`);
  await click('.nav-item[data-view="quickcalc"]');
  await ready('qcDeptTablesWrap');
  await delay(350);
  assert.equal(await evaluate(`getQcUsedRowCount(1)`),502,'大量粘贴保存重启后所有行保留');
  assert.equal(await cell('qcDeptTablesWrap',502,priceCol),1.7,'大量粘贴末行数值在重启后可见');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(502,${priceCol}).getCellStyleData().fs`),13,'新增行自动匹配本表字号');
  const qcShot = await call('Page.captureScreenshot',{format:'png'});
  const qcScreenshot = path.join(os.tmpdir(),'lms-quickcalc-compact.png');
  await fs.writeFile(qcScreenshot,Buffer.from(qcShot.data,'base64'));
  console.log(`SCREENSHOT: ${qcScreenshot}`);
  await call('Emulation.setDeviceMetricsOverride',{width:1000,height:680,deviceScaleFactor:1,mobile:false});
  await delay(250);
  const small = await evaluate(`(() => {const host=document.querySelector('#qcDeptTablesWrap .lms-sheet-host').getBoundingClientRect();return {top:host.top,bottom:host.bottom,height:host.height};})()`);
  assert.ok(small.height>500 && small.bottom<=680,`最小窗口仍保留足够表格空间 ${JSON.stringify(small)}`);
  console.log(`PASS: 实际页面输入/保存/切月及SQLite重启、连续行录入/禁止跳行/清空收拢/撤销重做/固定列、紧凑布局与侧栏${width}px`);
};
