const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

module.exports = async ({ evaluate, call, delay, mouse, key }) => {
  await call('Emulation.setDeviceMetricsOverride', { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
  await delay(700);
  assert.equal(await evaluate('window.fixtureReady'), true, '实际页面初始化成功');
  assert.ok(await evaluate('document.querySelector("#spreadsheetWrap canvas") !== null'), '真实 Canvas 表格');
  const result = await call('Page.captureScreenshot', { format: 'png' });
  const screenshot = path.join(require('node:os').tmpdir(), 'lms-spreadsheet-engine.png');
  await fs.writeFile(screenshot, Buffer.from(result.data, 'base64'));
  console.log(`SCREENSHOT: ${screenshot}`);
  const cellPoint = (r,c) => evaluate(`(() => {const rect=LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(${r},${c}).getCellRect();const canvas=Array.from(document.querySelectorAll('#spreadsheetWrap canvas'),el=>el.getBoundingClientRect()).sort((a,b)=>b.width*b.height-a.width*a.height)[0];return {x:canvas.x+rect.x+rect.width/2,y:canvas.y+rect.y+rect.height/2};})()`);
  const from = await cellPoint(2,2);
  const to = await cellPoint(3,3);
  await mouse('mousePressed', from, {button:'left',buttons:1,clickCount:1});
  for (let n=1;n<=8;n++) await mouse('mouseMoved',{x:from.x+(to.x-from.x)*n/8,y:from.y+(to.y-from.y)*n/8},{button:'left',buttons:1});
  await mouse('mouseReleased',to,{button:'left',buttons:0,clickCount:1});
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getSelection().getActiveRange().getA1Notation()`), 'C3:D4', 'Canvas真实拖选四格');
  assert.equal(await evaluate('getSelection().toString()'), '', 'Canvas拖选无原生文字选区');
  await call('Browser.grantPermissions', {permissions:['clipboardReadWrite','clipboardSanitizedWrite']});
  await key('c',67,2);
  await delay(100);
  assert.equal((await evaluate('navigator.clipboard.readText()')).replace(/\r\n/g,'\n').trim(), '1\t2\n3\t4', '真实Ctrl+C复制区域');
  await evaluate(`navigator.clipboard.writeText('7\\t8\\n9\\t10')`);
  await key('v',86,2);
  await delay(150);
  assert.deepEqual(await evaluate('[_weRowMap.r1.emps[1],_weRowMap.r1.emps[2],_weRowMap.r2.emps[1],_weRowMap.r2.emps[2]]'), [7,8,9,10], '真实Ctrl+V矩阵粘贴');
  await evaluate('undo()');
  await delay(100);
  await evaluate('clearHistory()');
  const at = await cellPoint(2,2);
  await mouse('mousePressed',at,{button:'left',buttons:1,clickCount:1});
  await mouse('mouseReleased',at,{button:'left',buttons:0,clickCount:1});
  await delay(100);
  await key('ArrowRight',39);
  await delay(50);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getSelection().getActiveRange().getA1Notation()`),'D3','真实方向键移格');
  await key('ArrowDown',40,8);
  await delay(50);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getSelection().getActiveRange().getA1Notation()`),'D3:D4','真实Shift扩选');
  const firstCell = await cellPoint(2,2);
  await mouse('mousePressed',firstCell,{button:'left',buttons:1,clickCount:1});
  await mouse('mouseReleased',firstCell,{button:'left',buttons:0,clickCount:1});
  await call('Input.dispatchKeyEvent',{type:'keyDown',key:'6',code:'Digit6',windowsVirtualKeyCode:54,text:'6'});
  await call('Input.dispatchKeyEvent',{type:'keyUp',key:'6',code:'Digit6',windowsVirtualKeyCode:54});
  await key('Enter',13);
  await delay(100);
  assert.equal(await evaluate('_weRowMap.r1.emps[1]'),6,'键入数字并Enter提交');
  await key('z',90,2);
  await delay(100);
  assert.equal(await evaluate('_weRowMap.r1.emps[1]'),1,'真实Ctrl+Z只撤销一次');
  await evaluate('clearHistory()');
  const editPoint = await cellPoint(2,2);
  await mouse('mousePressed',editPoint,{button:'left',buttons:1,clickCount:1});
  await mouse('mouseReleased',editPoint,{button:'left',buttons:0,clickCount:1});
  await delay(150);
  for (const digit of '123') {
    await call('Input.dispatchKeyEvent',{type:'keyDown',key:digit,code:`Digit${digit}`,windowsVirtualKeyCode:digit.charCodeAt(0),text:digit});
    await call('Input.dispatchKeyEvent',{type:'keyUp',key:digit,code:`Digit${digit}`,windowsVirtualKeyCode:digit.charCodeAt(0)});
  }
  await delay(150);
  await key('Enter',13);
  await delay(150);
  assert.equal(await evaluate(`Number(LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2).getValue())`),123,'多位数字提交后保持可见');
  assert.equal(await evaluate('_weRowMap.r1.emps[1]'),123,'多位数字写回模型');
  await evaluate('undo()');
  await delay(100);
  await evaluate('clearHistory()');
  // 引擎使用同一条命令链处理录入、粘贴与撤销；先核对批量写回。
  await evaluate(`void LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2,2,2).setValues([[7,8],[9,10]])`);
  await delay(50);
  assert.deepEqual(await evaluate('[_weRowMap.r1.emps[1],_weRowMap.r1.emps[2],_weRowMap.r2.emps[1],_weRowMap.r2.emps[2]]'), [7,8,9,10], '四格写回业务数据');
  assert.equal(await evaluate('_undoStack.length'), 1, '批量录入一条历史');
  assert.deepEqual(await evaluate(`(() => { const s=LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet(); return [Number(s.getRange(2,4).getValue()),Number(s.getRange(3,4).getValue())]; })()`), [15,19], '行合计同步');
  await evaluate('undo()');
  await delay(100);
  assert.deepEqual(await evaluate('[_weRowMap.r1.emps[1],_weRowMap.r1.emps[2]]'), [1,2], '撤销恢复数据');
  assert.equal(await evaluate(`Number(LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2).getValue())`), 1, '撤销后的画面数值');
  await evaluate('redo()');
  await delay(100);
  assert.deepEqual(await evaluate('[_weRowMap.r1.emps[1],_weRowMap.r1.emps[2]]'), [7,8], '重做恢复数据');
  await evaluate(`void LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2,1,2).setValues([[11,1.2]])`);
  assert.deepEqual(await evaluate('[_weRowMap.r1.emps[1],_weRowMap.r1.emps[2]]'), [7,8], '非法整数整块拒绝');
  await evaluate(`void LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(1,2).setValue('篡改表头')`);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(1,2).getValue()`), '张三', '表头只读');
  await evaluate(`void LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2).setBackgroundColor('#ff0000')`);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2).getCellStyleData().bg.rgb`),'#ff0000','设置单元格格式');
  await evaluate('undo()');
  assert.notEqual(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2).getCellStyleData().bg.rgb`),'#ff0000','格式撤销');
  await evaluate('redo()');
  await evaluate(`void LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().setColumnWidth(2,140)`);
  await evaluate('renderSpreadsheet()');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.getActiveSheet().getRange(2,2).getCellStyleData().bg.rgb`),'#ff0000','刷新保留格式');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('spreadsheetWrap').book.save().sheets.work.columnData[2].w`),140,'刷新保留列宽');
  assert.ok(await evaluate(`Object.values(savedSettings).some(value=>JSON.parse(value).work?.columns['emp-1']?.w===140)`),'格式通过设置API写入数据库');
  await evaluate(`document.getElementById('spreadsheetWrap').style.display='none'; _currentView='quickcalc'; clearHistory(); renderQcDeptTables();`);
  await delay(400);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getSheets().length`), 2, '部门工作表标签');
  const qcPoint = await evaluate(`(() => {const i=LmsSpreadsheet.getInstance('qcDeptTablesWrap');const rect=i.book.getActiveSheet().getRange(1,1).getCellRect();const canvas=Array.from(document.querySelectorAll('#qcDeptTablesWrap canvas'),el=>el.getBoundingClientRect()).sort((a,b)=>b.width*b.height-a.width*a.height)[0];return {x:canvas.x+rect.x+rect.width/2,y:canvas.y+rect.y+rect.height/2};})()`);
  await mouse('mousePressed',qcPoint,{button:'left',buttons:1,clickCount:1});
  await mouse('mouseReleased',qcPoint,{button:'left',buttons:0,clickCount:1});
  await key('c',67,2);
  await delay(100);
  assert.equal((await evaluate('navigator.clipboard.readText()')).trim(),'5','切换页面后的真实复制');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().setActiveRange(LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,0))`);
  await evaluate(`navigator.clipboard.write([new ClipboardItem({
    'text/plain':new Blob(['3.75\\t12\\t13'],{type:'text/plain'}),
    'text/html':new Blob(['<table><tr><td style="background-color:#abcdef"><font color="#123456">3.75</font></td><td>12</td><td>13</td></tr></table>'],{type:'text/html'})
  })])`);
  await key('v',86,2);
  await delay(100);
  assert.deepEqual(await evaluate(`[_qcDeptRows['1_0'][10],_qcState.qtyData['1_0,1'],_qcState.qtyData['1_0,2']]`), [3.75,12,13], '单价小数与两名员工写回');
  assert.equal(await evaluate(`Number(LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,3).getValue())`), 25, '快捷计算行合计');
  await delay(550);
  assert.ok(await evaluate('saves.length > 0'), '接回原有自动保存');
  assert.equal(await evaluate(`document.querySelector('#qcDeptTablesWrap .lms-sheet-hint')`),null,'快捷计算不显示选格提示');
  assert.equal(await evaluate(`Array.from(document.querySelectorAll('#qcDeptTablesWrap button')).some(button=>/添加行|添加一行|删除选中行/.test(button.textContent))`),false,'快捷计算不显示行管理按钮');
  const blankPoint = await evaluate(`(() => {const rect=LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(5,1).getCellRect();const canvas=Array.from(document.querySelectorAll('#qcDeptTablesWrap canvas'),el=>el.getBoundingClientRect()).sort((a,b)=>b.width*b.height-a.width*a.height)[0];return {x:canvas.x+rect.x+rect.width/2,y:canvas.y+rect.y+rect.height/2};})()`);
  await mouse('mousePressed',blankPoint,{button:'left',buttons:1,clickCount:1});
  await mouse('mouseReleased',blankPoint,{button:'left',buttons:0,clickCount:1});
  for (const digit of '24') {
    await call('Input.dispatchKeyEvent',{type:'keyDown',key:digit,windowsVirtualKeyCode:digit.charCodeAt(0),text:digit});
    await call('Input.dispatchKeyEvent',{type:'keyUp',key:digit,windowsVirtualKeyCode:digit.charCodeAt(0)});
  }
  await key('Enter',13);
  await delay(100);
  assert.equal(await evaluate(`_qcState.qtyData['1_4,1']`),24,'原本未绑定的空白行可以直接键入');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(5,1).getCellStyleData().bg.rgb`),'#eff6ff','输入后自动启用整行样式');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().setActiveRange(LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(5,0))`);
  await evaluate(`navigator.clipboard.writeText('1.5\\t24\\t25\\n2.5\\t4\\t5')`);
  await key('v',86,2);
  await delay(150);
  assert.deepEqual(await evaluate(`[_qcDeptRows['1_4'][10],_qcState.qtyData['1_4,2'],_qcDeptRows['1_5'][10],_qcState.qtyData['1_5,2']]`),[1.5,25,2.5,5],'多行粘贴自动启用空白行');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().setActiveRange(LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(5,0,2,12))`);
  await key('Delete',46);
  await delay(100);
  assert.equal(await evaluate(`isQcRowUsed('1_4') || isQcRowUsed('1_5')`),false,'Delete清空后释放行数据');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(5,1).getCellStyleData().bg.rgb`),'#ffffff','清空后恢复白色空白行');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(5,3).getValue() ?? ''`),'','未用行的合计也保持空白');
  await evaluate('undo()');
  await delay(150);
  assert.equal(await evaluate(`_qcState.qtyData['1_5,2']`),5,'撤销恢复新启用行');
  await evaluate('redo()');
  await delay(150);
  assert.equal(await evaluate(`isQcRowUsed('1_5')`),false,'重做恢复空白行');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(199,1).setValue(15)`);
  assert.ok(await evaluate(`LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.save().sheets['dept-1'].rowCount`)>200,'录入到末尾时自动扩展空白行');
  assert.equal(await evaluate(`_qcState.qtyData['1_198,1']`),15,'新增末尾行映射正确');
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(10,0,1,2).setValues([[3.5,1.2]])`);
  assert.equal(await evaluate(`isQcRowUsed('1_9')`),false,'空白行非法粘贴整块拒绝且不启用');
  console.log('PASS: 引擎复制粘贴、空白行直接录入/自动样式/清空/撤销重做/扩展、数值校验及自动保存');
};
