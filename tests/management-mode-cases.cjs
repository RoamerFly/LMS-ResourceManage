const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');

module.exports = async ({evaluate,call,click,key,delay,restartBackend}) => {
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  const waitFor = async expression => {
    for (let i=0;i<100;i++) {
      if (await evaluate(expression)) return;
      await delay(100);
    }
    throw new Error(`页面未就绪：${expression}`);
  };
  const loaded = () => waitFor(`document.getElementById('loadingOverlay')?.style.display==='none'`);
  const screenshot = async name => {
    const shot = await call('Page.captureScreenshot',{format:'png'});
    const file = path.join(os.tmpdir(),name+'.png');
    await fs.writeFile(file,Buffer.from(shot.data,'base64'));
    console.log('SCREENSHOT: '+file);
  };
  await loaded();
  assert.equal(await evaluate(`document.querySelector('.nav-item[data-view="members"]').textContent.trim()`),'人员管理','导航名称更新');
  assert.equal(await evaluate(`document.querySelector('.nav-item[data-view="departments"],.nav-item[data-view="prices"]')`),null,'独立部门与单价导航已合并');
  await click('.nav-item[data-view="members"]');
  await waitFor(`document.querySelector('#memberList .member-card') !== null`);
  const centered = await evaluate(`(() => {const button=document.getElementById('personnelDeptBtn').getBoundingClientRect();const bar=document.querySelector('.personnel-toolbar').getBoundingClientRect();return Math.abs(button.x+button.width/2-bar.x-bar.width/2);})()`);
  assert.ok(centered<2,`部门入口居中 ${centered}px`);
  await click('#personnelDeptBtn');
  await waitFor(`document.querySelector('.organization-branch') !== null`);
  assert.equal(await evaluate(`document.getElementById('modalBox').classList.contains('department-modal')`),true,'部门大弹窗');
  const treeLayout = await evaluate(`(() => {const modal=document.getElementById('modalBox').getBoundingClientRect();const root=document.querySelector('.organization-root').getBoundingClientRect();const parent=document.querySelector('.department-parent').getBoundingClientRect();const child=document.querySelector('.department-child').getBoundingClientRect();return {width:modal.width,height:modal.height,root:root.bottom,parent:parent.top,child:child.top,parentBottom:parent.bottom};})()`);
  assert.ok(treeLayout.width>1000 && treeLayout.height>700 && treeLayout.parent>treeLayout.root && treeLayout.child>treeLayout.parentBottom,'大部门与小部门自顶向下分支');
  await click('.organization-root > button');
  await call('Input.insertText',{text:'测试新部门'});
  await click('#dept-form-root [type="submit"]');
  await waitFor(`_state.departments.some(dept=>dept.name==='测试新部门')`);
  const deptId = await evaluate(`_state.departments.find(dept=>dept.name==='测试新部门').id`);
  await click(`[data-dept-id="${deptId}"] .department-node-actions .btn-secondary`);
  await call('Input.insertText',{text:'测试小部门'});
  await click(`#dept-form-${deptId} [type="submit"]`);
  await waitFor(`_state.subDepartments.some(sub=>sub.name==='测试小部门')`);
  const subId = await evaluate(`_state.subDepartments.find(sub=>sub.name==='测试小部门').id`);
  assert.equal(await evaluate(`get('/api/sub-departments').then(data=>data.find(sub=>sub.id===${subId}).dept_id)`),deptId,'树节点添加真实写入SQLite');
  await screenshot('lms-personnel-department-tree');
  await click('.department-modal-header > button');
  await click('#view-members button[onclick="showAddMemberModal()"]');
  await waitFor(`document.getElementById('m-dept') !== null`);
  assert.equal(await evaluate(`document.getElementById('modalBox').classList.contains('department-modal')`),false,'其他弹窗不继承部门布局');
  await evaluate(`document.getElementById('m-name').value='新人员';document.getElementById('m-dept').value='${deptId}';onDeptChange('m');document.getElementById('m-subdept').value='${subId}'`);
  await click('#modalBox button[onclick="doAddMember()"]');
  await waitFor(`_state.employees.some(emp=>emp.name==='新人员')`);
  assert.equal(await evaluate(`get('/api/employees').then(data=>data.find(emp=>emp.name==='新人员').sub_dept_id)`),subId,'人员页新部门立即可用于新增人员');

  await click('.nav-item[data-view="orders"]');
  await waitFor(`document.querySelector('#orderList .order-card') !== null`);
  await click('#orderPricesTab');
  await waitFor(`document.querySelector('#priceTable input[type="number"]') !== null`);
  assert.equal(await evaluate(`document.getElementById('orderRecordsPanel').hidden && !document.getElementById('orderPricesPanel').hidden`),true,'订单页内切换型号单价');
  await evaluate(`document.querySelector('#priceTable input[type="number"]').value='4.25';document.querySelector('#priceTable input[type="number"]').dispatchEvent(new Event('change'))`);
  await waitFor(`get('/api/price-table').then(data=>Object.values(data.prices).includes(4.25))`);
  await click('#orderRecordsTab');
  assert.equal(await evaluate(`_currentView`),'orders','单价返回订单保留同一页面');
  await click('#orderPricesTab');
  await waitFor(`Array.from(document.querySelectorAll('#priceTable input[type="number"]')).some(input=>Number(input.value)===4.25)`);
  await screenshot('lms-orders-prices-merged');

  // 保留常规模式原有来源，极简模式始终使用快捷计算。
  await evaluate(`toggleQcSalary(false)`);
  await click('.nav-item[data-view="settings"]');
  await waitFor(`_currentView==='settings'`);
  await click('label:has(#s-minimalMode)');
  await waitFor(`_currentView==='quickcalc' && LmsSpreadsheet.getInstance('qcDeptTablesWrap')?.ready`);
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.sidebar')).display`),'none','极简模式完全删除左侧导航占用');
  assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('#minimalNav button'),button=>button.textContent)`),['人员管理','总工资表','系统设置'],'顶部只有三个导航卡片');
  const header = await evaluate(`(() => {const nav=document.getElementById('minimalNav').getBoundingClientRect();const buttons=Array.from(nav ? document.querySelectorAll('#minimalNav button'):[],button=>button.getBoundingClientRect());return {offset:Math.abs(nav.x+nav.width/2-innerWidth/2),salary:buttons[1].width,other:buttons[0].width,height:buttons[1].height,otherHeight:buttons[0].height,main:document.querySelector('.main').getBoundingClientRect().width};})()`);
  assert.ok(header.offset<2 && header.salary>header.other && header.height>header.otherHeight && header.main===1440,'导航居中，工资按钮稍大，主内容全宽');
  assert.equal(await evaluate('getSalarySource()'),'qc','极简模式工资来源强制快捷计算');
  assert.equal(await evaluate(`localStorage.getItem('useQcSalary')`),'false','保留常规模式的工资来源偏好');
  const priceCol = await evaluate(`Array.from(LmsSpreadsheet.getInstance('qcDeptTablesWrap').sheets.get('dept-1').cells.values()).find(cell=>cell.isPrice && cell.input.dataset.subId==='1').col`);
  const qtyCol = await evaluate(`Array.from(LmsSpreadsheet.getInstance('qcDeptTablesWrap').sheets.get('dept-1').cells.values()).find(cell=>cell.input?.dataset.key==='1_0,1').col`);
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,${priceCol}).setValue(2.75)`);
  await evaluate(`void LmsSpreadsheet.getInstance('qcDeptTablesWrap').book.getActiveSheet().getRange(1,${qtyCol}).setValue(88)`);
  await click('#minimalNav [data-view="salary"]');
  await waitFor(`_currentView==='salary' && document.getElementById('salaryContent').textContent.includes('242.00')`);
  assert.equal(await evaluate(`get('/api/quick-calc-save?year=2026&month=9').then(data=>data.qty_data['1_0,1'])`),88,'顶部导航离开主页先保存快捷计算数据');
  await click('.minimal-home');
  await waitFor(`_currentView==='quickcalc' && LmsSpreadsheet.getInstance('qcDeptTablesWrap')?.ready`);
  await screenshot('lms-minimal-quickcalc-home');
  await click('#minimalNav [data-view="members"]');
  await waitFor(`_currentView==='members'`);
  await click('#personnelDeptBtn');
  await waitFor(`document.querySelector('[data-sub-dept-id="${subId}"]') !== null`);
  await click('.department-modal-header > button');
  await click('#view-members .btn-back-home');
  await waitFor(`_currentView==='quickcalc'`);
  await evaluate(`navigateTo('work')`);
  assert.equal(await evaluate('_currentView'),'quickcalc','极简模式旧入口不能进入做货编辑');
  await restartBackend();
  await call('Page.reload');
  await loaded();
  assert.equal(await evaluate('_currentView'),'quickcalc','重启后直接以快捷计算为主页');
  assert.equal(await evaluate('isMinimalMode() && getSalarySource()==="qc"'),true,'极简模式与工资来源持久化');
  assert.equal(await evaluate(`get('/api/app-settings-all').then(data=>data.ui_minimalMode)`),true,'极简设置保存到数据库');
  await call('Emulation.setDeviceMetricsOverride',{width:1000,height:680,deviceScaleFactor:1,mobile:false});
  await delay(300);
  const narrow = await evaluate(`(() => {const nav=document.getElementById('minimalNav').getBoundingClientRect();const host=document.querySelector('#qcDeptTablesWrap .lms-sheet-host').getBoundingClientRect();return {left:nav.left,right:nav.right,center:nav.x+nav.width/2,hostHeight:host.height,hostBottom:host.bottom};})()`);
  assert.ok(narrow.left>=0 && narrow.right<=1000 && Math.abs(narrow.center-500)<2 && narrow.hostHeight>450 && narrow.hostBottom<=680,'小窗口顶部导航与表格布局可用');
  await click('#minimalNav [data-view="members"]');
  await waitFor(`_currentView==='members'`);
  assert.ok(await evaluate(`(() => {const button=document.getElementById('personnelDeptBtn').getBoundingClientRect();const bar=document.querySelector('.personnel-toolbar').getBoundingClientRect();return Math.abs(button.x+button.width/2-bar.x-bar.width/2)<2;})()`),'小窗口部门入口仍居中');
  await click('#minimalNav [data-view="settings"]');
  await waitFor(`_currentView==='settings'`);
  await click('label:has(#s-minimalMode)');
  await waitFor(`!isMinimalMode() && _currentView==='settings'`);
  assert.notEqual(await evaluate(`getComputedStyle(document.querySelector('.sidebar')).display`),'none','关闭极简模式恢复左栏');
  assert.equal(await evaluate('getSalarySource()'),'work','关闭极简恢复常规工资来源');
  await click('.nav-item[data-view="overview"]');
  await waitFor(`_currentView==='overview'`);
  assert.equal(await evaluate(`document.querySelector('.overview-card[data-view="departments"],.overview-card[data-view="prices"]')`),null,'主页不重复显示已合并功能');
  console.log('PASS: 人员与部门树新增、订单单价合并及保存、极简三卡片导航/全宽主页/工资来源/退出恢复/SQLite重启');
};
