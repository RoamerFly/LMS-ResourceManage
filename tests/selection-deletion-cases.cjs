const assert = require('node:assert/strict');

module.exports = async ({evaluate,call,click,key,mouse,delay,restartBackend}) => {
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  const waitFor = async expression => {
    for(let i=0;i<100;i++){if(await evaluate(expression))return;await delay(100);}
    throw new Error(`页面未就绪：${expression}`);
  };
  const ready = wrap => waitFor(`LmsSpreadsheet.getInstance('${wrap}')?.ready && !document.querySelector('#${wrap} [data-u-comp="workbench-skeleton-shimmer"]')`);
  const point = (wrap,row,col) => evaluate(`(() => {const i=LmsSpreadsheet.getInstance('${wrap}'),s=i.book.getActiveSheet(),r=s.getRange(${row},${col}).getCellRect(),c=[...i.host.querySelectorAll('canvas')].sort((a,b)=>b.clientWidth*b.clientHeight-a.clientWidth*a.clientHeight)[0].getBoundingClientRect();return {x:c.x+(r.x+r.width/2)*s.getZoom(),y:c.y+(r.y+r.height/2)*s.getZoom()};})()`);
  const drag = async (wrap,from,to) => {
    const a=await point(wrap,...from),b=await point(wrap,...to);
    await mouse('mousePressed',a,{button:'left',buttons:1,clickCount:1});
    for(let n=1;n<=8;n++)await mouse('mouseMoved',{x:a.x+(b.x-a.x)*n/8,y:a.y+(b.y-a.y)*n/8},{button:'left',buttons:1});
    await mouse('mouseReleased',b,{button:'left',buttons:0,clickCount:1}); await delay(100);
  };
  const values = (wrap,row,col,h,w) => evaluate(`(() => {const s=LmsSpreadsheet.getInstance('${wrap}').book.getActiveSheet();return Array.from({length:${h}},(_,r)=>Array.from({length:${w}},(_,c)=>s.getRange(${row}+r,${col}+c).getRawValue()));})()`);
  const set = (wrap,row,col,data) => evaluate(`void LmsSpreadsheet.getInstance('${wrap}').book.getActiveSheet().getRange(${row},${col},${data.length},${data[0].length}).setValues(${JSON.stringify(data)})`);
  const undo = async wrap => { await key('z',90,2); await ready(wrap); await delay(150); };
  const redo = async wrap => { await key('y',89,2); await ready(wrap); await delay(150); };
  const empty = data => data.every(row=>row.every(value=>value==null||value===''));
  await waitFor(`document.getElementById('loadingOverlay')?.style.display==='none'`);
  await click('.nav-item[data-view="quickcalc"]'); await ready('qcDeptTablesWrap');
  const qc='qcDeptTablesWrap', expected=[[1,2,3,4,5],[6,7,8,9,0],[11,12,13,14,15]];
  await set(qc,1,3,expected); await evaluate('clearHistory()');
  await drag(qc,[1,3],[3,7]);
  assert.deepEqual(await evaluate(`(() => {const r=LmsSpreadsheet.getInstance('${qc}').book.getActiveSheet().getSelection().getActiveRange().getRange();return [r.startRow,r.startColumn,r.endRow,r.endColumn];})()`),[1,3,3,7],'真实鼠标框选整个区域');
  await key('Backspace',8); await delay(200);
  assert.ok(empty(await values(qc,1,3,3,5)),'Backspace清空整个框选区域');
  assert.equal(await evaluate('_undoStack.length'),1,'批量删除只生成一条历史');
  await undo(qc); assert.deepEqual(await values(qc,1,3,3,5),expected,'一次撤销恢复全部内容和显式零');
  await redo(qc); assert.ok(empty(await values(qc,1,3,3,5)),'一次重做清空整个区域');
  await undo(qc);
  await drag(qc,[1,3],[3,7]); await key('F2',113); await delay(100);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('${qc}').book.isCellEditing()`),true,'多格选区进入编辑状态');
  await key('Backspace',8); await delay(200);
  assert.ok(empty(await values(qc,1,3,3,5)),'编辑状态Backspace也清空选区');
  await undo(qc); assert.deepEqual(await values(qc,1,3,3,5),expected,'编辑状态批量删除可一次撤销');
  await drag(qc,[1,3],[3,7]); await key('F2',113); await key('a',65,2); await call('Input.insertText',{text:'99'});
  await key('Backspace',8); await delay(200);
  assert.ok(empty(await values(qc,1,3,3,5)),'含未提交内容时仍批量清空');
  await undo(qc); const withDraft=expected.map(row=>[...row]);withDraft[0][0]=99;
  assert.deepEqual(await values(qc,1,3,3,5),withDraft,'撤销恢复删除前的未提交编辑值');
  await drag(qc,[1,3],[3,7]); await key('F2',113); await key('Backspace',8); await key('z',90,2); await ready(qc); await delay(150);
  assert.deepEqual(await values(qc,1,3,3,5),withDraft,'编辑状态删除后立即Ctrl+Z可恢复全部内容');
  await drag(qc,[1,3],[1,3]);
  const multiStart=await point(qc,1,6),multiEnd=await point(qc,3,7);
  await mouse('mousePressed',multiStart,{button:'left',buttons:1,clickCount:1,modifiers:2});
  await mouse('mouseMoved',multiEnd,{button:'left',buttons:1,modifiers:2});
  await mouse('mouseReleased',multiEnd,{button:'left',buttons:0,clickCount:1,modifiers:2});await delay(100);
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('${qc}').book.getActiveSheet().getSelection().getActiveRangeList().length`),2,'Ctrl鼠标选择两个不连续区域');
  await key('Backspace',8);await delay(150);
  assert.ok(empty(await values(qc,1,6,3,2)),'删除所有不连续选区');
  assert.equal((await values(qc,1,3,1,1))[0][0],null,'第一个单格区域也清空');
  assert.equal((await values(qc,1,4,1,1))[0][0],2,'两个选区之间未选格保留');
  await undo(qc);assert.deepEqual(await values(qc,1,3,3,5),withDraft,'不连续选区一次撤销全部恢复');
  await drag(qc,[1,3],[3,7]); await key('Delete',46); await delay(150);
  assert.ok(empty(await values(qc,1,3,3,5)),'Delete也按整个区域清空'); await undo(qc);
  await drag(qc,[1,3],[1,3]); await key('F2',113); await key('a',65,2); await call('Input.insertText',{text:'123'});await key('Backspace',8);await key('Enter',13);await delay(150);
  assert.equal(Number((await values(qc,1,3,1,1))[0][0]),12,'单格编辑仍按字符退格');
  await drag(qc,[1,0],[3,8]); await key('Backspace',8); await delay(150);
  assert.ok(empty(await values(qc,1,3,3,5)),'选区含统计列与空列时清空可编辑内容');
  assert.equal(await evaluate(`LmsSpreadsheet.getInstance('${qc}').book.getActiveSheet().getRange(0,3).getValue()`),'折边单价','保留只读表头');
  await undo(qc);
  await click('.nav-item[data-view="work"]'); await ready('spreadsheetWrap');
  const work='spreadsheetWrap',workData=[[21,22],[31,32],[41,42]];
  await evaluate(`addWorkRow();addWorkRow()`);await ready(work);await set(work,2,2,workData);await evaluate('clearHistory()');
  await drag(work,[2,2],[4,3]);await key('Backspace',8);await delay(200);
  assert.ok(empty(await values(work,2,2,3,2)),'做货编辑多行多列Backspace清空');
  await undo(work);assert.deepEqual(await values(work,2,2,3,2),workData,'做货编辑一次撤销恢复整块');
  await evaluate('autoSaveWorkRecords()'); await restartBackend(); await call('Page.reload');
  await waitFor(`document.getElementById('loadingOverlay')?.style.display==='none'`);await click('.nav-item[data-view="work"]');await ready(work);
  assert.deepEqual(await values(work,2,2,3,2),workData,'撤销后的完整数据写入SQLite并可重启恢复');
  console.log('PASS: Backspace鼠标框选整块清空/单次撤销重做/编辑与未提交值/显式零/单格字符退格/只读列/做货页与SQLite重启');
};
